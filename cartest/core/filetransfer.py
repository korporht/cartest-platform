from __future__ import annotations

import hashlib
import math
import shlex
import subprocess
import tempfile
import threading
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

#: 本地分块读写缓冲
BUFFER_SIZE = 4 * 1024 * 1024
#: 小文件阈值（<2GB 直推）
SMALL_FILE_LIMIT = 2 * 1024**3
#: 分块基准大小（MB）
CHUNK_BASE_MB = 500
#: 分块数上限（超过则上调块大小）
CHUNK_MAX_COUNT = 100
#: 块大小封顶（MB）
CHUNK_CAP_MB = 1024
#: 设备端合并脚本路径
DEVICE_SCRIPT_PATH = "/data/local/tmp/_adb_push_merge.sh"

OnLog = Callable[[str, str], None] | None
OnProgress = Callable[[int, int, float, float, float], None] | None


@dataclass
class PushResult:
    ok: bool
    message: str


def chunk_size_mb(file_size: int, base: int = CHUNK_BASE_MB,
                  max_count: int = CHUNK_MAX_COUNT, cap: int = CHUNK_CAP_MB) -> int:
    """自动分块大小（MB）：基准 base；块数超过 max_count 时按 size/max_count 上调，封顶 cap"""
    size_mb = file_size / 1024 / 1024
    if size_mb > 0 and size_mb / base > max_count:
        return min(math.ceil(size_mb / max_count), cap)
    return base


def build_merge_script(remote_dir: str, filename: str, num_chunks: int,
                       final_path: str) -> str:
    """设备端合并脚本：分块存在性检查 → 合并 → 大小比对 → 清理 → 输出日志"""
    q = shlex.quote
    return "\n".join([
        "#!/system/bin/sh",
        "set -e",
        "",
        "# Auto-generated by cartest.core.filetransfer - DO NOT EDIT",
        f"CHUNK_DIR={q(remote_dir)}",
        f"FILENAME={q(filename)}",
        f"FINAL_PATH={q(final_path)}",
        f"NUM_CHUNKS={num_chunks}",
        "",
        'MERGE_LOG="$CHUNK_DIR/_merge.log"',
        'echo "[$(date)] Starting merge..." > "$MERGE_LOG"',
        "",
        "# 验证所有分块存在",
        "MISSING=0",
        "i=0",
        'while [ "$i" -lt "$NUM_CHUNKS" ]; do',
        '    CHUNK=$(printf "%s/%s.chunk%04d" "$CHUNK_DIR" "$FILENAME" "$i")',
        '    if [ ! -f "$CHUNK" ]; then',
        '        echo "[$(date)] ERROR: Missing chunk: $CHUNK" >> "$MERGE_LOG"',
        "        MISSING=1",
        "        break",
        "    fi",
        "    i=$((i + 1))",
        "done",
        "",
        'if [ "$MISSING" -eq 1 ]; then',
        '    echo "[$(date)] ABORT: Missing chunks detected" >> "$MERGE_LOG"',
        "    exit 1",
        "fi",
        "",
        "# 合并分块",
        'echo "[$(date)] Merging $NUM_CHUNKS chunks..." >> "$MERGE_LOG"',
        "MERGED_SIZE=0",
        "i=0",
        'while [ "$i" -lt "$NUM_CHUNKS" ]; do',
        '    CHUNK=$(printf "%s/%s.chunk%04d" "$CHUNK_DIR" "$FILENAME" "$i")',
        '    cat "$CHUNK" >> "$FINAL_PATH"',
        '    CHUNK_SIZE=$(wc -c < "$CHUNK")',
        "    MERGED_SIZE=$((MERGED_SIZE + CHUNK_SIZE))",
        "    i=$((i + 1))",
        "done",
        "",
        "# 验证合并后文件大小",
        'FINAL_SIZE=$(wc -c < "$FINAL_PATH")',
        'if [ "$FINAL_SIZE" -ne "$MERGED_SIZE" ]; then',
        '    echo "[$(date)] ERROR: Size mismatch expected=$MERGED_SIZE got=$FINAL_SIZE" >> "$MERGE_LOG"',
        "    exit 1",
        "fi",
        'echo "[$(date)] Merge OK size=$FINAL_SIZE" >> "$MERGE_LOG"',
        "",
        "# 清理分块",
        'echo "[$(date)] Cleaning up chunks..." >> "$MERGE_LOG"',
        "i=0",
        'while [ "$i" -lt "$NUM_CHUNKS" ]; do',
        '    CHUNK=$(printf "%s/%s.chunk%04d" "$CHUNK_DIR" "$FILENAME" "$i")',
        '    rm -f "$CHUNK"',
        "    i=$((i + 1))",
        "done",
        "",
        'cat "$MERGE_LOG"',
        'rm -f "$MERGE_LOG"',
        "exit 0",
    ])


def md5_file(path: str | Path) -> str:
    digest = hashlib.md5()
    with open(path, "rb") as f:
        for data in iter(lambda: f.read(8192), b""):
            digest.update(data)
    return digest.hexdigest()


def _default_runner(cmd: list[str], timeout: float):  # pragma: no cover - 薄适配
    from .adb import session
    return session().run(cmd, timeout)


class FilePusher:
    """大文件推送执行器（无 UI 依赖；经回调上报）

    Args:
        runner:       ``runner(cmd, timeout) -> result``；默认 ``AdbSession.run``
        on_log:       ``(level, msg)``，level ∈ info/warn/error
        on_progress:  ``(index, total, pct, mbps, eta_sec)``
        cancel:       取消事件（UI 取消时 set）
        retry:        单块推送重试次数
        retry_delay:  重试间隔（秒）
        wait_reconnect: 设备断连等待上限（秒；0 = 不等待）
    """

    def __init__(self, *, runner=None, on_log: OnLog = None, on_progress: OnProgress = None,
                 cancel: threading.Event | None = None, retry: int = 3,
                 retry_delay: float = 3.0, wait_reconnect: float = 120.0,
                 poll_interval: float = 2.0) -> None:
        self._runner = runner or _default_runner
        self._on_log = on_log
        self._on_progress = on_progress
        self._cancel = cancel or threading.Event()
        self._retry = max(1, retry)
        self._retry_delay = retry_delay
        self._wait_reconnect = wait_reconnect
        self._poll = poll_interval

    # ── 基础 ────────────────────────────────
    def _log(self, level: str, msg: str) -> None:
        if self._on_log:
            self._on_log(level, msg)

    def _run(self, cmd: list[str], timeout: float = 300):
        try:
            return self._runner(cmd, timeout)
        except subprocess.TimeoutExpired:
            return None

    def _cancelled(self) -> bool:
        return self._cancel.is_set()

    def _device_present(self) -> bool:
        r = self._run(["adb", "devices"], timeout=10)
        if r is None:
            return False
        for line in r.stdout.splitlines():
            parts = line.strip().split()
            if len(parts) >= 2 and parts[1] == "device":
                return True
        return False

    def _wait_device(self) -> bool:
        if self._wait_reconnect <= 0:
            return False
        self._log("warn", f"等待设备重新连接（最长 {self._wait_reconnect:.0f}s）...")
        deadline = time.time() + self._wait_reconnect
        while time.time() < deadline:
            if self._cancelled():
                return False
            if self._device_present():
                self._log("info", "设备已重新连接")
                return True
            time.sleep(self._poll)
        return False

    # ── 主流程 ──────────────────────────────
    def push(self, local_path: str | Path, remote_path: str,
             chunk_mb: int | None = None) -> PushResult:
        local = Path(local_path)
        if not local.is_file():
            return PushResult(False, f"文件不存在: {local}")
        size = local.stat().st_size
        if not self._device_present():
            return PushResult(False, "未发现可用设备（adb devices 为空）")

        self._log("info", f"源文件: {local}（{size / 1024 / 1024:.1f} MB）")
        self._log("info", f"目标路径: {remote_path}")
        self._prepare_device(remote_path)

        # 显式给出 chunk_mb = 强制分块（含小于阈值的文件，便于联调/测试）
        if chunk_mb is None and size < SMALL_FILE_LIMIT:
            return self._push_small(local, remote_path)
        return self._push_large(local, remote_path, size, chunk_mb)

    def _prepare_device(self, remote_path: str) -> None:
        self._log("info", "设备准备: adb root ...")
        self._run(["adb", "root"], timeout=30)
        self._log("info", "设备准备: adb remount ...")
        self._run(["adb", "remount"], timeout=30)
        remote_dir = remote_path.rsplit("/", 1)[0] if "/" in remote_path else ""
        if remote_dir:
            self._run(["adb", "shell", f"mkdir -p {shlex.quote(remote_dir)}"], timeout=15)
        r = self._run(["adb", "shell", f"df {shlex.quote(remote_dir or remote_path)}"],
                      timeout=15)
        if r is not None and r.returncode == 0:
            self._log("info", f"设备可用空间检查: {r.stdout.strip().splitlines()[-1][:60]}")

    def _push_small(self, local: Path, remote_path: str) -> PushResult:
        self._log("info", "小文件模式：直接 adb push")
        r = self._run(["adb", "push", str(local), remote_path], timeout=600)
        if r is None or r.returncode != 0:
            err = (r.stderr.strip() if r else "超时") or "unknown"
            return PushResult(False, f"adb push 失败: {err}")
        self._log("info", "push 完成，开始 MD5 校验...")
        local_md5 = md5_file(local)
        remote_md5 = self._remote_md5(remote_path)
        if local_md5 and local_md5 == remote_md5:
            return PushResult(True, "全部完成，MD5 校验通过")
        return PushResult(False, f"MD5 校验失败（local={local_md5[:12]}… remote={remote_md5[:12]}…）")

    def _push_large(self, local: Path, remote_path: str, size: int,
                    chunk_mb: int | None) -> PushResult:
        chunk_mb = chunk_mb or chunk_size_mb(size)
        chunk_bytes = chunk_mb * 1024 * 1024
        total = math.ceil(size / chunk_bytes)
        self._log("info", f"分块策略: {chunk_mb} MB × {total} 块")
        self._log("info", "MD5 预计算启动（推送期间后台进行）")
        md5_box: dict = {}

        def _precompute() -> None:
            try:
                md5_box["md5"] = md5_file(local)
            except Exception:  # noqa: BLE001
                md5_box["md5"] = ""

        md5_thread = threading.Thread(target=_precompute, daemon=True)
        md5_thread.start()

        started = time.time()
        for i in range(total):
            if self._cancelled():
                self._cleanup(local, remote_path, total)
                return PushResult(False, "已取消（清理本地与设备端分块，下次从头重推）")
            chunk_local = Path(f"{local}.chunk{i:04d}")
            local_md5, err = self._write_chunk(local, chunk_local, i, chunk_bytes, size)
            if err:
                self._cleanup(local, remote_path, total)
                return PushResult(False, f"分块 {i} 本地写入失败: {err}")
            if not self._push_chunk(chunk_local, f"{remote_path}.chunk{i:04d}", i):
                self._log("error", f"分块 {i} 推送失败，已重试 {self._retry} 次；可重新运行从头重推")
                self._cleanup(local, remote_path, total)
                return PushResult(False, f"分块 {i} 推送失败（已重试 {self._retry} 次）")
            remote_md5 = self._remote_md5(f"{remote_path}.chunk{i:04d}")
            if remote_md5 != local_md5:
                self._log("warn", f"分块 {i} MD5 不一致（local={local_md5[:12]}… "
                                  f"remote={remote_md5[:12]}…），继续（终验兜底）")
            chunk_local.unlink(missing_ok=True)
            elapsed = max(time.time() - started, 0.001)
            done_mb = min((i + 1) * chunk_bytes, size) / 1024 / 1024
            pct = min((i + 1) * chunk_bytes, size) / size * 100
            mbps = done_mb / elapsed
            eta = (size - min((i + 1) * chunk_bytes, size)) / 1024 / 1024 / max(mbps, 0.1)
            if self._on_progress:
                self._on_progress(i + 1, total, pct, mbps, eta)

        elapsed = max(time.time() - started, 0.001)
        self._log("info", f"推送完成: {total} 块, 耗时 {elapsed:.1f}s, "
                          f"平均 {size / 1024 / 1024 / elapsed:.1f} MB/s")

        if self._cancelled():
            self._cleanup(local, remote_path, total)
            return PushResult(False, "已取消")

        self._log("info", "设备端合并...")
        if not self._merge_on_device(remote_path, total):
            self._cleanup(local, remote_path, total)
            return PushResult(False, "设备端合并失败")

        if md5_thread.is_alive():
            md5_thread.join()
        local_md5 = md5_box.get("md5") or md5_file(local)
        remote_md5 = self._remote_md5(remote_path)
        if local_md5 and local_md5 == remote_md5:
            return PushResult(True, "全部完成，MD5 校验通过")
        return PushResult(False, f"MD5 校验失败（local={local_md5[:12]}… remote={remote_md5[:12]}…）")

    # ── 分块细节 ────────────────────────────
    def _write_chunk(self, local: Path, chunk_local: Path, index: int,
                     chunk_bytes: int, size: int) -> tuple[str, str]:
        offset = index * chunk_bytes
        length = min(chunk_bytes, size - offset)
        digest = hashlib.md5()
        try:
            with open(local, "rb") as src, open(chunk_local, "wb") as dst:
                src.seek(offset)
                remaining = length
                while remaining > 0:
                    data = src.read(min(BUFFER_SIZE, remaining))
                    if not data:
                        break
                    dst.write(data)
                    digest.update(data)
                    remaining -= len(data)
        except OSError as exc:
            chunk_local.unlink(missing_ok=True)
            return "", str(exc)
        return digest.hexdigest(), ""

    def _push_chunk(self, chunk_local: Path, chunk_remote: str, index: int) -> bool:
        for attempt in range(1, self._retry + 1):
            if self._cancelled():
                return False
            r = self._run(["adb", "push", str(chunk_local), chunk_remote], timeout=600)
            if r is not None and r.returncode == 0:
                return True
            err = (r.stderr.strip() if r else "超时") or "unknown error"
            self._log("warn", f"分块 {index} 推送失败（第 {attempt}/{self._retry} 次）: {err}")
            if not self._device_present() and not self._wait_device():
                return False
            if attempt < self._retry and self._retry_delay > 0:
                time.sleep(self._retry_delay)
        return False

    def _remote_md5(self, remote_path: str) -> str:
        r = self._run(["adb", "shell", f"md5sum {shlex.quote(remote_path)}"], timeout=300)
        if r is None or r.returncode != 0 or not r.stdout.strip():
            return ""
        return r.stdout.split()[0]

    def _merge_on_device(self, remote_path: str, total: int) -> bool:
        remote_dir = remote_path.rsplit("/", 1)[0] if "/" in remote_path else "/data/local/tmp"
        filename = remote_path.rsplit("/", 1)[-1]
        script = build_merge_script(remote_dir, filename, total, remote_path)
        script_local = Path(tempfile.gettempdir()) / "_adb_push_merge.sh"
        script_local.write_text(script, encoding="utf-8", newline="\n")
        try:
            r = self._run(["adb", "push", str(script_local), DEVICE_SCRIPT_PATH], timeout=30)
            if r is None or r.returncode != 0:
                self._log("error", "合并脚本推送失败")
                return False
            r = self._run(["adb", "shell", f"sh {DEVICE_SCRIPT_PATH}"], timeout=3600)
            if r is None or r.returncode != 0:
                self._log("error", f"合并脚本执行失败: "
                                   f"{(r.stderr.strip() if r else '超时')[:200]}")
                return False
            for line in r.stdout.strip().splitlines():
                self._log("info", f"[设备] {line}")
            return True
        finally:
            script_local.unlink(missing_ok=True)
            self._run(["adb", "shell", f"rm -f {DEVICE_SCRIPT_PATH}"], timeout=15)

    # ── 清理 ────────────────────────────────
    def _cleanup(self, local: Path, remote_path: str, total: int) -> None:
        removed = 0
        for i in range(total):
            p = Path(f"{local}.chunk{i:04d}")
            if p.exists():
                p.unlink(missing_ok=True)
                removed += 1
        if removed:
            self._log("info", f"已清理本地分块 {removed} 个")
        if self._device_present():
            for i in range(total):
                self._run(["adb", "shell", f"rm -f {remote_path}.chunk{i:04d}"], timeout=10)
            self._log("info", "已清理设备端残留分块")


def push_file(local_path: str | Path, remote_path: str, **kwargs) -> PushResult:
    """便捷入口（一次性推送）"""
    return FilePusher(**kwargs).push(local_path, remote_path)
